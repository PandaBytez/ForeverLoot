-- Data sourced from Jweyant/forever-xp
local _G = getfenv(0)
local addonname = ...
local AtlasLoot = _G.AtlasLoot
local data = AtlasLoot.ItemDB:Get(addonname)
if not data then return end

local function NextFreeSlot(tbl)
	local used = {}
	local maxSlot = 0
	for _, entry in ipairs(tbl) do
		if type(entry[1]) == "number" then
			used[entry[1]] = true
			if entry[1] > maxSlot then maxSlot = entry[1] end
		end
	end
	return used, maxSlot
end

local function MergeIntoCategory(profKey, catIndex, prefDiff, itemIDs)
	local prof = data[profKey]
	local cat = prof and prof.items and prof.items[catIndex]
	if not cat then return end
	local tbl = cat[prefDiff] or cat[1] or cat[2] or cat[3] or cat[4]
	if not tbl then
		tbl = {}
		cat[prefDiff] = tbl
	end
	local used, maxSlot = NextFreeSlot(tbl)
	-- Start on the next page if current page is nearly full, or continue after maxSlot
	local slot = maxSlot + 1
	for _, id in ipairs(itemIDs) do
		while (slot % 100) == 0 or (slot % 100) > 30 or used[slot] do
			if (slot % 100) > 30 or (slot % 100) == 0 then
				slot = (math.floor(slot / 100) + 1) * 100 + 1
			else
				slot = slot + 1
			end
		end
		table.insert(tbl, { slot, "i" .. id })
		used[slot] = true
		slot = slot + 1
	end
end

